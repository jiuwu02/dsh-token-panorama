/**
 * The three default instructions this plugin ships.
 *
 * They live here, with no imports of their own, because the configuration
 * schema, the compaction engine, and the question answerer all need them:
 * schema.js imports them to build its defaults, while contextops.js and ask.js
 * use them as the fallback when a user leaves an instruction blank. Keeping the
 * strings in one dependency-free module is what breaks the old import cycle
 * (schema -> ask -> contextops -> ledger -> store -> schema) that made a bare
 * `import("lib/ask.js")` throw a temporal-dead-zone ReferenceError.
 *
 * The wording is pinned by test/prompts.test.mjs: all three share the same
 * five-module skeleton and half-width punctuation, and each keeps the one
 * clause its call site depends on. Edit the wording, keep the shape.
 */

